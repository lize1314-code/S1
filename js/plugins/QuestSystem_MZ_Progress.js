/*:
 * @target MZ
 * @plugindesc v1.5.1 任務進度：所有取得物品自動同步、戰鬥擊殺自動同步
 * @author ChatGPT
 *
 * @help
 * ============================================================================
 * QuestSystem_MZ_Progress v1.5.1
 * ============================================================================
 *
 * 本插件負責：
 *
 * 1. 所有實際取得物品，自動同步收集任務
 * 2. 戰鬥擊殺，自動同步擊殺任務
 * 3. 防止收集物品任務重複計算
 *
 * ============================================================================
 *
 * 插件順序：
 *
 * 1. QuestSystem_MZ_Core v1.5.1
 * 2. QuestSystem_MZ_Core_Report v1.5.1
 * 3. QuestSystem_MZ_Progress v1.5.1
 * 4. QuestSystem_MZ_UI v1.5.1
 *
 * ============================================================================
 *
 * 【收集物品任務】
 *
 * 任務設定：
 *
 * type   = item
 * target = 43
 * amount = 5
 *
 * 玩家取得物品 ID 43：
 *
 * 0/5
 * ↓
 * 1/5
 *
 * 再取得 4 個：
 *
 * 1/5
 * ↓
 * 5/5
 * ↓
 * 任務完成
 *
 * ============================================================================
 *
 * 【重要】
 *
 * 事件中不需要使用 AddItemProgress。
 *
 * 只要正常使用：
 *
 * ◆增減物品
 *   蘑菇孢子 +1
 *
 * 本插件就會自動增加任務進度。
 *
 * ============================================================================
 *
 * 【戰鬥擊殺任務】
 *
 * 在敵人資料庫的「備註」加入：
 *
 * <QuestEnemy:1>
 *
 * 其中 1 是敵人的資料庫 ID。
 *
 * 例如：
 *
 * 任務：
 *
 * type   = kill
 * target = 1
 * amount = 5
 *
 * 戰鬥中擊殺 1 隻符合：
 *
 * <QuestEnemy:1>
 *
 * 的敵人：
 *
 * 0/5
 * ↓
 * 1/5
 *
 * ============================================================================
 *
 * 【多種敵人】
 *
 * 同一個敵人可以設定多個任務標籤：
 *
 * <QuestEnemy:1>
 * <QuestEnemy:2>
 *
 * ============================================================================
 *
 * 【本插件不負責】
 *
 * 任務開始
 * 任務完成
 * 任務回報
 * 任務追蹤器 UI
 * 任務完成通知
 *
 * 以上功能由其他 QuestSystem 插件負責。
 *
 * ============================================================================
 */

(() => {
    "use strict";

    const PLUGIN_NAME = "QuestSystem_MZ_Progress";
    const VERSION = "1.5.1";


    // =========================================================================
    // 防止插件重複載入
    // =========================================================================
    //
    // 必須在攔截 Game_Party.gainItem 之前檢查。
    //
    // 如果 Progress 插件被重複放入插件管理器，
    // 第二次載入會直接停止，不會再次攔截 gainItem。
    //
    // =========================================================================

    if (
        typeof Game_Party !== "undefined" &&
        Game_Party.prototype._questProgressAutoItem
    ) {
        console.warn(
            `${PLUGIN_NAME} v${VERSION}：插件已經載入，跳過第二次載入。`
        );

        return;
    }


    if (
        typeof Game_Party !== "undefined"
    ) {
        Game_Party.prototype._questProgressAutoItem = true;
    }


    // =========================================================================
    // 確認 RPG Maker MZ 核心類別
    // =========================================================================

    if (
        typeof Game_System === "undefined" ||
        typeof Game_Party === "undefined"
    ) {

        console.error(
            `${PLUGIN_NAME}：找不到 RPG Maker MZ 核心類別。`
        );

        return;
    }


    // =========================================================================
    // 確認 QuestSystem_MZ_Core
    // =========================================================================

    if (
        typeof window !== "undefined" &&
        !window.QuestSystemMZ
    ) {

        console.warn(
            `${PLUGIN_NAME}：找不到 QuestSystem_MZ_Core 的全域物件。`
            + " 將繼續執行，但請確認插件順序。"
        );
    }


    // =========================================================================
    // 收集物品任務
    // =========================================================================
    //
    // 所有實際取得物品都會經過 Game_Party.gainItem。
    //
    // 因此：
    //
    // 戰鬥掉落
    // 寶箱
    // NPC
    // 採集
    // 商店購買
    // 其他事件增減物品
    //
    // 都可以自動偵測。
    //
    // =========================================================================

    const _QuestProgress_Game_Party_gainItem =
        Game_Party.prototype.gainItem;


    Game_Party.prototype.gainItem =
        function(
            item,
            amount,
            includeEquip
        ) {

            // -------------------------------------------------------------
            // 取得物品前的數量
            // -------------------------------------------------------------

            const beforeCount =
                item
                    ? this.numItems(item)
                    : 0;


            // -------------------------------------------------------------
            // 執行 RPG Maker MZ 原本的 gainItem
            // -------------------------------------------------------------

            _QuestProgress_Game_Party_gainItem.call(
                this,
                item,
                amount,
                includeEquip
            );


            // -------------------------------------------------------------
            // 基本檢查
            // -------------------------------------------------------------

            if (
                !item ||
                Number(amount || 0) <= 0 ||
                !$gameSystem
            ) {

                return;
            }


            // -------------------------------------------------------------
            // 取得物品後的實際數量
            // -------------------------------------------------------------

            const afterCount =
                this.numItems(item);


            // -------------------------------------------------------------
            // 計算實際增加數量
            //
            // 例如：
            //
            // 原本 2 個
            // 增加 1 個
            // 現在 3 個
            //
            // gained = 1
            //
            // 如果背包滿了：
            //
            // 原本 99 個
            // 增加 1 個
            // 現在仍然 99 個
            //
            // gained = 0
            //
            // -------------------------------------------------------------

            const gained =
                Math.max(
                    0,
                    afterCount - beforeCount
                );


            if (gained <= 0) {
                return;
            }


            // -------------------------------------------------------------
            // 取得目前進行中的任務
            // -------------------------------------------------------------

            if (
                typeof $gameSystem.activeQuests !==
                "function"
            ) {
                return;
            }


            const quests =
                $gameSystem.activeQuests();


            if (
                !quests ||
                !quests.length
            ) {

                return;
            }


            // -------------------------------------------------------------
            // 檢查所有進行中的收集任務
            // -------------------------------------------------------------

            for (
                const quest of quests
            ) {

                if (!quest) {
                    continue;
                }


                // ---------------------------------------------------------
                // 只處理收集物品任務
                // ---------------------------------------------------------

                if (
                    quest.type !==
                    "item"
                ) {

                    continue;
                }


                // ---------------------------------------------------------
                // 任務目標物品 ID
                // ---------------------------------------------------------

                if (
                    Number(
                        quest.target
                    ) !==
                    Number(
                        item.id
                    )
                ) {

                    continue;
                }


                // ---------------------------------------------------------
                // 確認 Core 有 addQuestProgress
                // ---------------------------------------------------------

                if (
                    typeof $gameSystem.addQuestProgress !==
                    "function"
                ) {

                    console.warn(
                        `${PLUGIN_NAME}：`
                        + "找不到 $gameSystem.addQuestProgress。"
                    );

                    continue;
                }


                // ---------------------------------------------------------
                // 自動增加任務進度
                // ---------------------------------------------------------

                $gameSystem.addQuestProgress(
                    quest.id,
                    gained
                );

            }

        };


    // =========================================================================
    // 戰鬥擊殺任務
    // =========================================================================

    function processQuestEnemyKills() {

        if (!$gameSystem) {
            return;
        }


        // -------------------------------------------------------------
        // 確認 activeQuests
        // -------------------------------------------------------------

        if (
            typeof $gameSystem.activeQuests !==
            "function"
        ) {

            return;
        }


        // -------------------------------------------------------------
        // 取得目前進行中的任務
        // -------------------------------------------------------------

        const quests =
            $gameSystem.activeQuests();


        if (
            !quests ||
            !quests.length
        ) {

            return;
        }


        // -------------------------------------------------------------
        // 確認 $gameTroop
        // -------------------------------------------------------------

        if (
            typeof $gameTroop === "undefined" ||
            !$gameTroop ||
            typeof $gameTroop.members !== "function"
        ) {

            return;
        }


        // -------------------------------------------------------------
        // 檢查本次戰鬥所有敵人
        // -------------------------------------------------------------

        for (
            const enemy of
            $gameTroop.members()
        ) {

            if (
                !enemy ||
                !enemy.isDead()
            ) {

                continue;
            }


            // ---------------------------------------------------------
            // 取得資料庫敵人
            // ---------------------------------------------------------

            const databaseEnemy =
                enemy.enemy();


            if (!databaseEnemy) {
                continue;
            }


            // ---------------------------------------------------------
            // 取得敵人備註
            // ---------------------------------------------------------

            const note =
                databaseEnemy.note ||
                "";


            // ---------------------------------------------------------
            // 搜尋：
            //
            // <QuestEnemy:1>
            //
            // <QuestEnemy:2>
            //
            // <QuestEnemy:1>
            // <QuestEnemy:2>
            //
            // 都可以。
            // ---------------------------------------------------------

            const matches = [];


            const regex =
                /<QuestEnemy\s*:\s*([^>]+)>/gi;


            let match;


            while (
                (
                    match =
                        regex.exec(note)
                )
            ) {

                matches.push(
                    String(
                        match[1]
                    ).trim()
                );

            }


            if (!matches.length) {
                continue;
            }


            // -------------------------------------------------------------
            // 比對任務
            // -------------------------------------------------------------

            for (
                const quest of quests
            ) {

                if (!quest) {
                    continue;
                }


                // ---------------------------------------------------------
                // 只處理擊殺任務
                // ---------------------------------------------------------

                if (
                    quest.type !==
                    "kill"
                ) {

                    continue;
                }


                // ---------------------------------------------------------
                // 敵人備註 ID
                // 是否符合任務 target
                // ---------------------------------------------------------

                if (
                    matches.includes(
                        String(
                            quest.target
                        )
                    )
                ) {

                    // -----------------------------------------------------
                    // 確認 Core 有 addQuestProgress
                    // -----------------------------------------------------

                    if (
                        typeof $gameSystem.addQuestProgress !==
                        "function"
                    ) {

                        console.warn(
                            `${PLUGIN_NAME}：`
                            + "找不到 $gameSystem.addQuestProgress。"
                        );

                        continue;
                    }


                    // -----------------------------------------------------
                    // 增加 1 隻擊殺進度
                    // -----------------------------------------------------

                    $gameSystem.addQuestProgress(
                        quest.id,
                        1
                    );

                }

            }

        }

    }


    // =========================================================================
    // 戰鬥勝利
    // =========================================================================
    //
    // 在 RPG Maker MZ 原本的戰鬥勝利流程中，
    // 加入任務擊殺計算。
    //
    // =========================================================================

    if (
        typeof BattleManager !== "undefined"
    ) {

        const _QuestProgress_BattleManager_processVictory =
            BattleManager.processVictory;


        BattleManager.processVictory =
            function() {

                // ---------------------------------------------------------
                // 計算本場戰鬥的擊殺任務
                // ---------------------------------------------------------

                processQuestEnemyKills();


                // ---------------------------------------------------------
                // 執行 RPG Maker MZ 原本的戰鬥勝利
                // ---------------------------------------------------------

                _QuestProgress_BattleManager_processVictory.call(
                    this
                );

            };

    }


    // =========================================================================
    // 開發者除錯工具
    // =========================================================================
    //
    // F8 Console：
    //
    // QuestSystemProgress
    //
    // =========================================================================

    if (
        typeof window !== "undefined"
    ) {

        window.QuestSystemProgress = {

            version: VERSION,

            processQuestEnemyKills:
                processQuestEnemyKills,

            refresh: function() {

                if (
                    typeof SceneManager !== "undefined" &&
                    SceneManager._scene
                ) {

                    const scene =
                        SceneManager._scene;


                    if (
                        typeof scene.refreshQuestTracker ===
                        "function"
                    ) {

                        scene.refreshQuestTracker();

                    }


                    if (
                        typeof scene.refreshQuestWindows ===
                        "function"
                    ) {

                        scene.refreshQuestWindows();

                    }

                }

            }

        };

    }


    // =========================================================================
    // 完成載入
    // =========================================================================

    console.log(
        `${PLUGIN_NAME} v${VERSION} loaded.`
    );

})();