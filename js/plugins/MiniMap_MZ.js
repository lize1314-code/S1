/*:
 * @target MZ
 * @plugindesc v1.2.3 小地圖系統：右上固定、避開狀態欄、劇情期間隱藏
 * @author ChatGPT
 *
 * @help
 * ============================================================================
 * MiniMap_MZ v1.2.3
 * ============================================================================
 *
 * RPG Maker MZ 小地圖插件
 *
 * 功能：
 *
 * 1. 顯示目前地圖的小地圖
 * 2. 玩家顯示藍色圓點
 * 3. NPC / 事件顯示黃色圓點
 * 4. 玩家移動時同步更新
 * 5. 小地圖固定右上角
 * 6. 自動避開右上角狀態欄
 * 7. 支援 1280 × 720
 * 8. 支援手機橫向
 * 9. 地圖切換後自動重新建立
 * 10. 開場 / 劇情事件期間自動隱藏
 * 11. 劇情結束後自動顯示
 * 12. 不修改 rmmz_core.js
 * 13. 不使用 window.resize
 * 14. 不使用 orientationchange
 *
 * ============================================================================
 *
 * 【小地圖顯示規則】
 *
 * 開場事件執行中：
 *
 *     小地圖隱藏
 *
 * 開場事件結束：
 *
 *     小地圖自動顯示
 *
 * 一般遊戲：
 *
 *     小地圖持續顯示
 *
 * 之後遇到劇情事件：
 *
 *     小地圖暫時隱藏
 *
 * 劇情事件結束：
 *
 *     小地圖重新顯示
 *
 * ============================================================================
 *
 * 【小地圖位置】
 *
 * 小地圖固定右上方。
 *
 * MAP_TOP 預設 120。
 *
 * 用來避開右上角狀態欄及選單按鈕。
 *
 * ============================================================================
 *
 * 【事件顯示】
 *
 * 在事件「備註」中加入：
 *
 * <MiniMap>
 *
 * 就會顯示黃色標記。
 *
 * ============================================================================
 *
 * 【重要】
 *
 * 請關閉：
 *
 * UI_MapQuestLayout_Fix.js
 *
 * 避免其他插件重新修改 UI 尺寸。
 *
 */

/*:
 * @param Map Width
 * @text 小地圖寬度
 * @type number
 * @min 150
 * @max 600
 * @default 300
 *
 * @param Map Height
 * @text 小地圖高度
 * @type number
 * @min 100
 * @max 400
 * @default 200
 *
 * @param Map Margin
 * @text 小地圖右側距離
 * @type number
 * @min 0
 * @max 300
 * @default 20
 *
 * @param Map Top
 * @text 小地圖上方距離
 * @type number
 * @min 0
 * @max 500
 * @default 120
 * @desc 小地圖從這個 Y 座標開始，避免與右上狀態欄重疊。
 *
 * @param Border Width
 * @text 邊框寬度
 * @type number
 * @min 1
 * @max 10
 * @default 3
 *
 * @param Background Opacity
 * @text 背景透明度
 * @type number
 * @min 0
 * @max 255
 * @default 220
 *
 * @param Player Size
 * @text 玩家標記大小
 * @type number
 * @min 2
 * @max 20
 * @default 8
 *
 * @param Event Size
 * @text 事件標記大小
 * @type number
 * @min 2
 * @max 20
 * @default 6
 *
 * @param Update Rate
 * @text 更新速度
 * @type number
 * @min 1
 * @max 60
 * @default 10
 *
 * @param Show Events
 * @text 顯示事件
 * @type boolean
 * @on 顯示
 * @off 隱藏
 * @default true
 *
 * @param Show Player
 * @text 顯示玩家
 * @type boolean
 * @on 顯示
 * @off 隱藏
 * @default true
 *
 */

(() => {

    "use strict";


    // =========================================================================
    // 插件名稱
    // =========================================================================

    const PLUGIN_NAME =
        "MiniMap_MZ";


    // =========================================================================
    // 讀取插件參數
    // =========================================================================

    const params =
        PluginManager.parameters(
            PLUGIN_NAME
        );


    // =========================================================================
    // 小地圖寬度
    // =========================================================================

    const MAP_WIDTH =
        Number(
            params["Map Width"] || 300
        );


    // =========================================================================
    // 小地圖高度
    // =========================================================================

    const MAP_HEIGHT =
        Number(
            params["Map Height"] || 200
        );


    // =========================================================================
    // 小地圖右側距離
    // =========================================================================

    const MAP_MARGIN =
        Number(
            params["Map Margin"] || 20
        );


    // =========================================================================
    // 小地圖上方距離
    // =========================================================================
    //
    // 預設 120。
    //
    // 讓小地圖避開右上角狀態欄。
    //
    // =========================================================================

    const MAP_TOP =
        Number(
            params["Map Top"] || 120
        );


    // =========================================================================
    // 邊框寬度
    // =========================================================================

    const BORDER_WIDTH =
        Number(
            params["Border Width"] || 3
        );


    // =========================================================================
    // 背景透明度
    // =========================================================================

    const BACKGROUND_OPACITY =
        Number(
            params["Background Opacity"] || 220
        );


    // =========================================================================
    // 玩家標記大小
    // =========================================================================

    const PLAYER_SIZE =
        Number(
            params["Player Size"] || 8
        );


    // =========================================================================
    // 事件標記大小
    // =========================================================================

    const EVENT_SIZE =
        Number(
            params["Event Size"] || 6
        );


    // =========================================================================
    // 更新速度
    // =========================================================================

    const UPDATE_RATE =
        Number(
            params["Update Rate"] || 10
        );


    // =========================================================================
    // 是否顯示事件
    // =========================================================================

    const SHOW_EVENTS =
        String(
            params["Show Events"] || "true"
        ) === "true";


    // =========================================================================
    // 是否顯示玩家
    // =========================================================================

    const SHOW_PLAYER =
        String(
            params["Show Player"] || "true"
        ) === "true";


    // =========================================================================
    // 判斷目前是否正在執行事件
    // =========================================================================
    //
    // 這裡不再使用：
    //
    // 0020 開關
    //
    // 也不再使用：
    //
    // Hidden Map IDs
    //
    // 完全依照 RPG Maker MZ 的事件狀態判斷。
    //
    // =========================================================================

    function isEventRunning() {

        if (
            !$gameMap
        ) {

            return false;
        }


        return $gameMap.isEventRunning();
    }


    // =========================================================================
    // Window_MiniMap
    // =========================================================================

    class Window_MiniMap
        extends Window_Base {


        // =====================================================================
        // 初始化
        // =====================================================================

        initialize(
            rect
        ) {

            super.initialize(
                rect
            );


            this._lastMapId =
                0;


            this._lastPlayerX =
                -1;


            this._lastPlayerY =
                -1;


            this._frameCounter =
                0;


            this._mapBitmap =
                null;


            this.opacity =
                255;


            this.backOpacity =
                0;


            this.createMiniMapBitmap();


            this.refresh();
        }


        // =====================================================================
        // 建立背景 Bitmap
        // =====================================================================

        createMiniMapBitmap() {

            const width =
                this.contentsWidth();


            const height =
                this.contentsHeight();


            this._mapBitmap =
                new Bitmap(
                    width,
                    height
                );


            this._mapBitmap.fillRect(
                0,
                0,
                width,
                height,
                "rgba(15,15,15," +
                (
                    BACKGROUND_OPACITY /
                    255
                ) +
                ")"
            );
        }


        // =====================================================================
        // 更新
        // =====================================================================

        update() {

            super.update();


            this._frameCounter++;


            if (
                this._frameCounter <
                UPDATE_RATE
            ) {

                return;
            }


            this._frameCounter =
                0;


            if (
                !$gameMap ||
                !$gamePlayer
            ) {

                return;
            }


            const mapId =
                $gameMap.mapId();


            const playerX =
                $gamePlayer.x;


            const playerY =
                $gamePlayer.y;


            // -------------------------------------------------------------
            // 地圖改變
            // -------------------------------------------------------------

            if (
                mapId !==
                this._lastMapId
            ) {

                this._lastMapId =
                    mapId;


                this._lastPlayerX =
                    playerX;


                this._lastPlayerY =
                    playerY;


                this.refresh();


                return;
            }


            // -------------------------------------------------------------
            // 玩家位置改變
            // -------------------------------------------------------------

            if (
                playerX !==
                this._lastPlayerX ||
                playerY !==
                this._lastPlayerY
            ) {

                this._lastPlayerX =
                    playerX;


                this._lastPlayerY =
                    playerY;


                this.refresh();
            }
        }


        // =====================================================================
        // 刷新
        // =====================================================================

        refresh() {

            this.contents.clear();


            if (
                !$gameMap
            ) {

                return;
            }


            if (
                !$dataMap
            ) {

                return;
            }


            this.drawMap();


            if (
                SHOW_EVENTS
            ) {

                this.drawEvents();
            }


            if (
                SHOW_PLAYER
            ) {

                this.drawPlayer();
            }


            this.drawBorder();


            // -------------------------------------------------------------
            // 所有內容畫完後只更新一次 Bitmap。
            //
            // 避免每個玩家 / 事件標記都呼叫 BaseTexture.update()。
            // -------------------------------------------------------------

            if (
                this.contents &&
                this.contents._baseTexture
            ) {

                this.contents
                    ._baseTexture
                    .update();
            }
        }


        // =====================================================================
        // 計算地圖縮放
        // =====================================================================

        mapScale() {

            const mapWidth =
                $gameMap.width();


            const mapHeight =
                $gameMap.height();


            if (
                mapWidth <= 0 ||
                mapHeight <= 0
            ) {

                return {
                    scaleX: 1,
                    scaleY: 1
                };
            }


            return {

                scaleX:
                    this.contentsWidth() /
                    mapWidth,

                scaleY:
                    this.contentsHeight() /
                    mapHeight
            };
        }


        // =====================================================================
        // 判斷格子是否可通行
        // =====================================================================

        isPassable(
            x,
            y
        ) {

            if (
                !$gameMap
            ) {

                return false;
            }


            if (
                x < 0 ||
                y < 0 ||
                x >= $gameMap.width() ||
                y >= $gameMap.height()
            ) {

                return false;
            }


            return (

                $gameMap.isPassable(
                    x,
                    y,
                    2
                ) ||

                $gameMap.isPassable(
                    x,
                    y,
                    4
                ) ||

                $gameMap.isPassable(
                    x,
                    y,
                    6
                ) ||

                $gameMap.isPassable(
                    x,
                    y,
                    8
                )
            );
        }


        // =====================================================================
        // 畫地圖
        // =====================================================================

        drawMap() {

            const mapWidth =
                $gameMap.width();


            const mapHeight =
                $gameMap.height();


            const scale =
                this.mapScale();


            for (
                let y = 0;
                y < mapHeight;
                y++
            ) {

                for (
                    let x = 0;
                    x < mapWidth;
                    x++
                ) {

                    const px =
                        Math.floor(
                            x *
                            scale.scaleX
                        );


                    const py =
                        Math.floor(
                            y *
                            scale.scaleY
                        );


                    const pw =
                        Math.ceil(
                            scale.scaleX
                        );


                    const ph =
                        Math.ceil(
                            scale.scaleY
                        );


                    if (
                        this.isPassable(
                            x,
                            y
                        )
                    ) {

                        this.contents
                            .paintOpacity =
                            180;


                        this.contents.fillRect(
                            px,
                            py,
                            pw,
                            ph,
                            "#666666"
                        );

                    } else {

                        this.contents
                            .paintOpacity =
                            80;


                        this.contents.fillRect(
                            px,
                            py,
                            pw,
                            ph,
                            "#202020"
                        );
                    }
                }
            }


            this.contents
                .paintOpacity =
                255;
        }


        // =====================================================================
        // 畫事件
        // =====================================================================

        drawEvents() {

            if (
                !$gameMap
            ) {

                return;
            }


            const scale =
                this.mapScale();


            const events =
                $gameMap.events();


            events.forEach(
                event => {

                    if (
                        !event
                    ) {

                        return;
                    }


                    if (
                        event._erased
                    ) {

                        return;
                    }


                    const eventData =
                        event.event();


                    if (
                        !eventData
                    ) {

                        return;
                    }


                    const note =
                        eventData.note ||
                        "";


                    // ---------------------------------------------------------
                    // 必須有 <MiniMap>
                    // ---------------------------------------------------------

                    if (
                        !/<MiniMap>/i.test(
                            note
                        )
                    ) {

                        return;
                    }


                    const px =
                        Math.floor(
                            (
                                event.x +
                                0.5
                            ) *
                            scale.scaleX
                        );


                    const py =
                        Math.floor(
                            (
                                event.y +
                                0.5
                            ) *
                            scale.scaleY
                        );


                    this.drawCircle(
                        px,
                        py,
                        EVENT_SIZE,
                        "#ffff00"
                    );
                }
            );
        }


        // =====================================================================
        // 畫玩家
        // =====================================================================

        drawPlayer() {

            if (
                !$gamePlayer
            ) {

                return;
            }


            const scale =
                this.mapScale();


            const px =
                Math.floor(
                    (
                        $gamePlayer.x +
                        0.5
                    ) *
                    scale.scaleX
                );


            const py =
                Math.floor(
                    (
                        $gamePlayer.y +
                        0.5
                    ) *
                    scale.scaleY
                );


            // -------------------------------------------------------------
            // 玩家白色外框
            // -------------------------------------------------------------

            this.drawCircle(
                px,
                py,
                PLAYER_SIZE + 2,
                "#ffffff"
            );


            // -------------------------------------------------------------
            // 玩家藍色圓點
            // -------------------------------------------------------------

            this.drawCircle(
                px,
                py,
                PLAYER_SIZE,
                "#00aaff"
            );
        }


        // =====================================================================
        // 畫圓
        // =====================================================================

        drawCircle(
            x,
            y,
            radius,
            color
        ) {

            const context =
                this.contents.context;


            if (
                !context
            ) {

                return;
            }


            context.save();


            context.fillStyle =
                color;


            context.beginPath();


            context.arc(
                x,
                y,
                radius,
                0,
                Math.PI * 2
            );


            context.fill();


            context.restore();
        }


        // =====================================================================
        // 畫邊框
        // =====================================================================

        drawBorder() {

            const width =
                this.contentsWidth();


            const height =
                this.contentsHeight();


            this.contents
                .paintOpacity =
                255;


            // -------------------------------------------------------------
            // 上
            // -------------------------------------------------------------

            this.contents.fillRect(
                0,
                0,
                width,
                BORDER_WIDTH,
                "#ffffff"
            );


            // -------------------------------------------------------------
            // 下
            // -------------------------------------------------------------

            this.contents.fillRect(
                0,
                height -
                BORDER_WIDTH,
                width,
                BORDER_WIDTH,
                "#ffffff"
            );


            // -------------------------------------------------------------
            // 左
            // -------------------------------------------------------------

            this.contents.fillRect(
                0,
                0,
                BORDER_WIDTH,
                height,
                "#ffffff"
            );


            // -------------------------------------------------------------
            // 右
            // -------------------------------------------------------------

            this.contents.fillRect(
                width -
                BORDER_WIDTH,
                0,
                BORDER_WIDTH,
                height,
                "#ffffff"
            );
        }
    }


    // =========================================================================
    // Scene_Map 建立所有視窗
    // =========================================================================

    const _Scene_Map_createAllWindows =
        Scene_Map.prototype.createAllWindows;


    Scene_Map.prototype.createAllWindows =
        function() {

            _Scene_Map_createAllWindows.call(
                this
            );


            this.createMiniMap();
        };


    // =========================================================================
    // 建立小地圖
    // =========================================================================
    //
    // ★ 固定右上方
    //
    // ★ 不跟 QuestTracker 並排
    //
    // ★ 不由 QuestSystem 控制位置
    //
    // ★ 不修改 MiniMap 尺寸
    //
    // =========================================================================

    Scene_Map.prototype.createMiniMap =
        function() {

            // -------------------------------------------------------------
            // 計算寬度
            // -------------------------------------------------------------

            const width =
                Math.min(
                    MAP_WIDTH,
                    Math.max(
                        150,
                        Graphics.boxWidth -
                        MAP_MARGIN * 2
                    )
                );


            // -------------------------------------------------------------
            // 計算高度
            // -------------------------------------------------------------

            const height =
                Math.min(
                    MAP_HEIGHT,
                    Math.max(
                        100,
                        Graphics.boxHeight -
                        MAP_TOP -
                        MAP_MARGIN
                    )
                );


            // -------------------------------------------------------------
            // ★ 固定右上
            // -------------------------------------------------------------

            const x =
                Graphics.boxWidth -
                width -
                MAP_MARGIN;


            // -------------------------------------------------------------
            // ★ 往下避開右上狀態欄
            // -------------------------------------------------------------

            const y =
                MAP_TOP;


            // -------------------------------------------------------------
            // Rectangle
            // -------------------------------------------------------------

            const rect =
                new Rectangle(
                    x,
                    y,
                    width,
                    height
                );


            // -------------------------------------------------------------
            // 建立 MiniMap
            // -------------------------------------------------------------

            this._miniMap =
                new Window_MiniMap(
                    rect
                );


            // -------------------------------------------------------------
            // 顯示層級
            // -------------------------------------------------------------

            this._miniMap.z =
                11;


            // -------------------------------------------------------------
            // ★ 開場 / 劇情期間隱藏
            //
            // 事件進行中 = 隱藏
            //
            // 事件結束 = 顯示
            // -------------------------------------------------------------

            this._miniMap.visible =
                !isEventRunning();


            // -------------------------------------------------------------
            // 加入場景
            // -------------------------------------------------------------

            this.addWindow(
                this._miniMap
            );
        };


    // =========================================================================
    // Scene_Map 更新
    // =========================================================================

    const _Scene_Map_update =
        Scene_Map.prototype.update;


    Scene_Map.prototype.update =
        function() {

            // -------------------------------------------------------------
            // RPG Maker 原本更新
            // -------------------------------------------------------------

            _Scene_Map_update.call(
                this
            );


            // -------------------------------------------------------------
            // 沒有 MiniMap
            // -------------------------------------------------------------

            if (
                !this._miniMap
            ) {

                return;
            }


            // -------------------------------------------------------------
            // ★ 判斷劇情是否正在進行
            // -------------------------------------------------------------

            const eventRunning =
                isEventRunning();


            // -------------------------------------------------------------
            // 劇情期間隱藏
            // -------------------------------------------------------------

            if (
                eventRunning
            ) {

                if (
                    this._miniMap.visible
                ) {

                    this._miniMap.hide();
                }


                return;
            }


            // -------------------------------------------------------------
            // 劇情結束後顯示
            // -------------------------------------------------------------

            if (
                !this._miniMap.visible
            ) {

                this._miniMap.show();


                // ---------------------------------------------------------
                // 劇情結束後立即刷新
                // ---------------------------------------------------------

                this._miniMap.refresh();
            }


            // -------------------------------------------------------------
            // 正常更新 MiniMap
            // -------------------------------------------------------------

            this._miniMap.update();
        };


    // =========================================================================
    // MiniMap 重新定位
    // =========================================================================
    //
    // ★ 只修改 x / y。
    //
    // ★ 不修改 width。
    //
    // ★ 不修改 height。
    //
    // ★ 不呼叫 QuestSystem。
    //
    // =========================================================================

    Scene_Map.prototype.updateMiniMapPosition =
        function() {

            if (
                !this._miniMap
            ) {

                return;
            }


            const width =
                this._miniMap.width;


            // -------------------------------------------------------------
            // 固定右上
            // -------------------------------------------------------------

            this._miniMap.x =
                Graphics.boxWidth -
                width -
                MAP_MARGIN;


            // -------------------------------------------------------------
            // 固定 Y
            // -------------------------------------------------------------

            this._miniMap.y =
                MAP_TOP;
        };


    // =========================================================================
    // 重要
    // =========================================================================
    //
    // 本版本完全不使用：
    //
    // window.addEventListener("resize", ...)
    //
    // window.addEventListener("orientationchange", ...)
    //
    // 避免 ResizeObserver 循環。
    //
    // =========================================================================


})();